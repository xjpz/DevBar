import Foundation

public enum ClipboardKind: String, Codable, Sendable {
    case text, url
}

public struct ClipboardEntry: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var kind: ClipboardKind
    public var text: String
    public var createdAt: Date
    public var lastCopiedAt: Date
    public var copyCount: Int
    public var isPinned: Bool
    public var revision: Int

    public var expiresAt: Date? { isPinned ? nil : lastCopiedAt.addingTimeInterval(7 * 86_400) }
    public var preview: String { String(text.prefix(120)) }
    public var byteCount: Int { text.utf8.count }
}

public struct ClipboardSummary: Codable, Equatable, Identifiable, Sendable {
    public var id: UUID
    public var kind: ClipboardKind
    public var preview: String
    public var lastCopiedAt: Date
    public var isPinned: Bool
    public var revision: Int

    public init(_ entry: ClipboardEntry) {
        id = entry.id
        kind = entry.kind
        preview = entry.preview
        lastCopiedAt = entry.lastCopiedAt
        isPinned = entry.isPinned
        revision = entry.revision
    }
}

public enum ClipboardFailure: String, Error, Codable, Sendable, LocalizedError {
    case unavailable, disabled, locked, rePair, unsupported, staleCursor, notFound, changed
    case invalidMessage, tooLarge, pinLimit, storage, timeout, cancelled, rateLimited

    public var errorDescription: String? {
        switch self {
        case .unavailable: String(localized: "clipboard_error_unavailable")
        case .disabled: String(localized: "clipboard_error_disabled")
        case .locked: String(localized: "clipboard_error_locked")
        case .rePair: String(localized: "clipboard_error_repair")
        case .unsupported: String(localized: "clipboard_error_unsupported")
        case .staleCursor: String(localized: "clipboard_error_stale")
        case .notFound: String(localized: "clipboard_error_not_found")
        case .changed: String(localized: "clipboard_error_changed")
        case .tooLarge: String(localized: "clipboard_error_too_large")
        case .pinLimit: String(localized: "clipboard_error_pin_limit")
        case .storage: String(localized: "clipboard_error_storage")
        case .timeout: String(localized: "clipboard_error_timeout")
        case .cancelled: String(localized: "clipboard_error_cancelled")
        case .rateLimited: String(localized: "clipboard_error_rate_limited")
        case .invalidMessage: String(localized: "clipboard_error_invalid")
        }
    }
}

public enum ClipboardContentPolicy {
    public static let maximumBytes = 32 * 1024
    public static let privateTypes: Set<String> = [
        "org.nspasteboard.ConcealedType", "org.nspasteboard.TransientType",
        "org.nspasteboard.AutoGeneratedType", "cc.xjpz.DevBar.clipboard.restore",
    ]

    public static func acceptedKind(text: String, types: Set<String> = []) -> ClipboardKind? {
        guard !text.trimmingCharacters(in: .whitespacesAndNewlines).isEmpty,
              text.utf8.count <= maximumBytes,
              let encoded = try? JSONEncoder().encode(text), encoded.count <= 34 * 1024,
              types.isDisjoint(with: privateTypes),
              !types.contains("public.file-url"),
              !types.contains("NSFilenamesPboardType") else { return nil }
        let upper = text.uppercased()
        guard !upper.contains("PRIVATE KEY-----"),
              !upper.contains("AUTHORIZATION: BEARER "),
              !upper.contains("AUTHORIZATION: BASIC ") else { return nil }
        if !text.contains(where: \.isWhitespace), let url = URL(string: text),
           ["https", "http"].contains(url.scheme?.lowercased() ?? ""), url.host != nil {
            return .url
        }
        // File paths and unsupported URL schemes remain ordinary text; never dereference them.
        guard !text.lowercased().hasPrefix("file://") else { return nil }
        return .text
    }
}

public struct ClipboardHistorySnapshot: Codable, Equatable, Sendable {
    public var schemaVersion = 1
    public var epoch = UUID()
    public var revision = 0
    public var entries: [ClipboardEntry] = []

    public init() {}

    public mutating func prune(now: Date) {
        let previous = entries
        entries.removeAll { $0.expiresAt.map { $0 <= now } ?? false }
        entries.sort { ($0.lastCopiedAt, $0.id.uuidString) > ($1.lastCopiedAt, $1.id.uuidString) }
        var count = 0
        entries = entries.filter { entry in
            if entry.isPinned { return true }
            count += 1
            return count <= 500
        }
        if entries != previous { revision += 1 }
    }

    @discardableResult
    public mutating func capture(_ text: String, now: Date = Date()) -> Bool {
        guard let kind = ClipboardContentPolicy.acceptedKind(text: text) else { return false }
        prune(now: now)
        revision += 1
        if let first = entries.first, first.kind == kind, first.text == text {
            entries[0].lastCopiedAt = now
            entries[0].copyCount += 1
            entries[0].revision = revision
        } else {
            entries.insert(ClipboardEntry(
                id: UUID(), kind: kind, text: text, createdAt: now, lastCopiedAt: now,
                copyCount: 1, isPinned: false, revision: revision
            ), at: 0)
        }
        prune(now: now)
        return true
    }

    public mutating func setPinned(_ id: UUID, pinned: Bool, now: Date = Date()) throws {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { throw ClipboardFailure.notFound }
        guard entries[index].isPinned != pinned else { return }
        guard !pinned || entries.filter(\.isPinned).count < 100 else { throw ClipboardFailure.pinLimit }
        revision += 1
        entries[index].isPinned = pinned
        entries[index].revision = revision
        prune(now: now)
    }

    public mutating func remove(_ id: UUID) {
        guard entries.contains(where: { $0.id == id }) else { return }
        entries.removeAll { $0.id == id }
        revision += 1
    }

    public mutating func clear(includingPinned: Bool) {
        entries.removeAll { includingPinned || !$0.isPinned }
        revision += 1
        if includingPinned { epoch = UUID() }
    }

    public mutating func markCopied(_ id: UUID, now: Date = Date()) throws {
        guard let index = entries.firstIndex(where: { $0.id == id }) else { throw ClipboardFailure.notFound }
        revision += 1
        entries[index].lastCopiedAt = now
        entries[index].copyCount += 1
        entries[index].revision = revision
        prune(now: now)
    }
}

public struct ClipboardRequest: Codable, Equatable, Sendable {
    public enum Operation: String, Codable, Sendable { case revision, list, detail }
    public var operation: Operation
    public var query: String
    public var pinnedOnly: Bool
    public var offset: Int
    public var epoch: UUID?
    public var revision: Int?
    public var itemID: UUID?
    public var cursor: String?

    public init(_ operation: Operation, query: String = "", pinnedOnly: Bool = false,
                offset: Int = 0, epoch: UUID? = nil, revision: Int? = nil, itemID: UUID? = nil, cursor: String? = nil) {
        self.operation = operation; self.query = query; self.pinnedOnly = pinnedOnly
        self.offset = offset; self.epoch = epoch; self.revision = revision; self.itemID = itemID
        self.cursor = cursor
    }
}

public struct ClipboardResponse: Codable, Equatable, Sendable {
    public var epoch: UUID
    public var revision: Int
    public var summaries: [ClipboardSummary] = []
    public var nextOffset: Int?
    public var nextCursor: String?
    public var entry: ClipboardEntry?
    public var manifest: [String: Int] = [:]

    public init(epoch: UUID, revision: Int) { self.epoch = epoch; self.revision = revision }
}

extension ClipboardHistorySnapshot {
    private struct Cursor: Codable, Equatable {
        var epoch: UUID
        var revision: Int
        var query: String
        var pinned: Bool
        var offset: Int
    }

    public func respond(to request: ClipboardRequest) throws -> ClipboardResponse {
        guard request.query.utf8.count <= 1024, request.offset >= 0, request.offset <= 600 else {
            throw ClipboardFailure.invalidMessage
        }
        var response = ClipboardResponse(epoch: epoch, revision: revision)
        switch request.operation {
        case .revision:
            response.manifest = Dictionary(uniqueKeysWithValues: entries.map { ($0.id.uuidString, $0.revision) })
        case .list:
            if request.offset > 0 {
                guard request.epoch == epoch, request.revision == revision,
                      let encoded = request.cursor, encoded.utf8.count <= 4096,
                      let data = Data(base64Encoded: encoded),
                      let cursor = try? JSONDecoder().decode(Cursor.self, from: data),
                      cursor == Cursor(epoch: epoch, revision: revision, query: request.query,
                                       pinned: request.pinnedOnly, offset: request.offset) else {
                    throw ClipboardFailure.staleCursor
                }
            }
            let filtered = entries.filter {
                (!request.pinnedOnly || $0.isPinned) &&
                (request.query.isEmpty || $0.text.localizedCaseInsensitiveContains(request.query))
            }
            let end = min(request.offset + 30, filtered.count)
            if request.offset < end { response.summaries = filtered[request.offset..<end].map(ClipboardSummary.init) }
            if end < filtered.count {
                response.nextOffset = end
                response.nextCursor = try JSONEncoder().encode(Cursor(epoch: epoch, revision: revision,
                    query: request.query, pinned: request.pinnedOnly, offset: end)).base64EncodedString()
            }
        case .detail:
            guard let entry = entries.first(where: { $0.id == request.itemID }) else { throw ClipboardFailure.notFound }
            guard request.epoch == epoch else { throw ClipboardFailure.changed }
            guard request.revision == entry.revision else { throw ClipboardFailure.changed }
            response.entry = entry
        }
        return response
    }
}
